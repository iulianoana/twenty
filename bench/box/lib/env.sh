# shellcheck shell=bash
# Environment lifecycle: main and one per preview. Each has its own git worktree, database
# (cloned from the seeded template), Redis, server and worker. See bench/README.md.

allocate_slot() {
  local name=$1 slot used meta
  if [[ $name == main ]]; then
    echo 0
    return
  fi
  declare -A taken=()
  for meta in "$ENVS_DIR"/*/meta; do
    [[ -f $meta ]] || continue
    taken[$(sed -n 's/^SLOT=//p' "$meta")]=1
  done
  used=0
  for slot in "${!taken[@]}"; do [[ $slot == 0 ]] || used=$((used + 1)); done
  ((used < MAX_PREVIEWS)) || die "capacity reached: $used previews running (MAX_PREVIEWS=$MAX_PREVIEWS)"
  for ((slot = 1; slot < 90; slot++)); do
    [[ -v "taken[$slot]" ]] || { echo "$slot"; return; }
  done
  die "no free slot"
}

write_env_file() {
  local name=$1 app_secret=$2
  load_env_meta "$name"
  load_bench_secrets
  local file
  file=$(env_secret_file "$name")
  umask 077
  cat >"$file" <<EOF
NODE_ENV=production
NODE_PORT=$PORT
SERVER_URL=$(env_url "$name")
PG_DATABASE_URL=postgres://twenty:$PG_PASSWORD@127.0.0.1:5432/$DB_NAME
REDIS_URL=redis://127.0.0.1:$REDIS_PORT
REDIS_PORT=$REDIS_PORT
APP_SECRET=$app_secret
ENCRYPTION_KEY=$ENCRYPTION_KEY
STORAGE_TYPE=local
STORAGE_LOCAL_PATH=$(env_dir "$name")/storage
TELEMETRY_ENABLED=false
MARKETPLACE_CATALOG_SYNC_CRON_ENABLED=false
DISABLE_DB_MIGRATIONS=true
DISABLE_CRON_JOBS_REGISTRATION=true
SIGN_IN_PREFILLED=false
IS_EMAIL_VERIFICATION_REQUIRED=false
IS_MULTIWORKSPACE_ENABLED=false
EMAIL_DRIVER=logger
PG_POOL_MAX_CONNECTIONS=10
NODE_OPTIONS=--max-old-space-size=3072
EOF
  umask 022
}

current_app_secret() {
  sed -n 's/^APP_SECRET=//p' "$(env_secret_file "$1")"
}

# Runs a twenty-server CLI command (dist/command/command) with the environment's settings.
twenty_command() {
  local name=$1 tree=$2
  shift 2
  (
    set -a
    # shellcheck disable=SC1090
    source "$(env_secret_file "$name")"
    set +a
    cd "$tree/packages/twenty-server" && as_bench node dist/command/command "$@"
  )
}

services() {
  local verb=$1 name=$2
  case $verb in
    start) systemctl start "twenty-redis@$name" "twenty-server@$name" "twenty-worker@$name" ;;
    restart)
      systemctl start "twenty-redis@$name"
      systemctl restart "twenty-server@$name" "twenty-worker@$name"
      ;;
    stop) systemctl stop "twenty-server@$name" "twenty-worker@$name" ;;
    stop-all) systemctl stop "twenty-server@$name" "twenty-worker@$name" "twenty-redis@$name" ;;
  esac
}

flush_redis() {
  local name=$1
  load_env_meta "$name"
  systemctl start "twenty-redis@$name"
  local i
  for ((i = 0; i < 20; i++)); do
    redis-cli -p "$REDIS_PORT" FLUSHALL >/dev/null 2>&1 && return 0
    sleep 0.5
  done
  die "redis for $name did not answer"
}

clone_database() {
  local name=$1
  load_env_meta "$name"
  load_bench_secrets
  psql_admin -c "DROP DATABASE IF EXISTS \"$DB_NAME\" WITH (FORCE)"
  psql_admin -c "CREATE DATABASE \"$DB_NAME\" TEMPLATE $TEMPLATE_DB STRATEGY FILE_COPY"
  psql_db "$DB_NAME" -f "$INFRA_DIR/box/sql/clone-tweaks.sql" >/dev/null
  rm -rf "$(env_dir "$name")/storage"
  cp -a "$TEMPLATE_STORAGE_DIR" "$(env_dir "$name")/storage"
  chown -R "$BENCH_USER:" "$(env_dir "$name")/storage"
}

# Rewrites the whole Caddyfile from the environments on disk and reloads Caddy. Previews are
# created and torn down at the same time, so the work holds one lock (in a subshell, so it is
# released here and not for the rest of the deploy) and writes a private temp file in the same
# directory, then moves it over the Caddyfile in one step.
regen_caddy() {
  (
    lock_exclusive caddy-regen
    local meta out
    out=$(mktemp /etc/caddy/Caddyfile.XXXXXX)
    {
      echo "# Generated by bench/box/bench; do not edit."
      for meta in "$ENVS_DIR"/*/meta; do
        [[ -f $meta ]] || continue
        (
          # shellcheck disable=SC1090
          source "$meta"
          # POST /metadata goes through the sign-up shim; everything else straight to the server.
          printf '%s {\n\t@metadata {\n\t\tmethod POST\n\t\tpath /metadata\n\t}\n\thandle @metadata {\n\t\treverse_proxy 127.0.0.1:%s {\n\t\t\theader_up X-Bench-Upstream 127.0.0.1:%s\n\t\t}\n\t}\n\thandle {\n\t\treverse_proxy 127.0.0.1:%s\n\t}\n}\n' \
            "$HOST" "$SIGNUP_SHIM_PORT" "$PORT" "$PORT"
        )
      done
    } >"$out"
    chmod 644 "$out"
    mv "$out" /etc/caddy/Caddyfile
    systemctl reload caddy || systemctl restart caddy
  )
}

# Ready = /healthz and /client-config answer 200 and / serves the built front, all through Caddy's TLS.
wait_ready() {
  local name=$1 timeout=${2:-240} host start
  host=$(env_host "$name")
  start=$(now_s)
  local -a curl_args=(-fsS --max-time 10 --resolve "$host:443:127.0.0.1")
  while (($(now_s) - start < timeout)); do
    if curl "${curl_args[@]}" -o /dev/null "https://$host/healthz" 2>/dev/null &&
      curl "${curl_args[@]}" -o /dev/null "https://$host/client-config" 2>/dev/null &&
      curl "${curl_args[@]}" "https://$host/" 2>/dev/null | grep -q 'window._env_'; then
      return 0
    fi
    sleep 2
  done
  log "not ready after ${timeout}s; recent server log:"
  journalctl -u "twenty-server@$name" -n 40 --no-pager -o cat 2>/dev/null | cut -c1-300 >&2 || true
  return 1
}

# Copies the base checkout's install and build outputs into a new worktree:
# node_modules as hard links (nothing writes into them after install), outputs as real copies.
copy_build_state() {
  local tree=$1 path
  while IFS= read -r -d '' path; do
    path=${path%/}
    case $path in
      .nx | */.local-storage | .local-storage | */logs | logs | .cache | */.cache) continue ;;
    esac
    as_bench mkdir -p "$tree/$(dirname "$path")"
    case $path in
      # Cache entries and installed packages are never modified in place, so hard links are safe.
      node_modules | */node_modules | .nx/cache) as_bench cp -al "$REPO_DIR/$path" "$tree/$path" ;;
      *) as_bench cp -a "$REPO_DIR/$path" "$tree/$path" ;;
    esac
  done < <(git -C "$REPO_DIR" ls-files -z --others --ignored --exclude-standard --directory)
}

fetch_commit() {
  local branch=$1 sha=$2
  (
    lock_exclusive repo-fetch
    if ! git -C "$REPO_DIR" cat-file -e "$sha^{commit}" 2>/dev/null; then
      as_bench git -C "$REPO_DIR" fetch --quiet --depth=300 origin "+refs/heads/$branch:refs/remotes/origin/$branch"
    fi
    git -C "$REPO_DIR" cat-file -e "$sha^{commit}" 2>/dev/null || die "commit $sha not found on $branch"
  )
}

create_env() {
  local name=$1 branch=$2 dir slot start
  dir=$(env_dir "$name")
  start=$(now_s)
  (
    lock_exclusive slots
    slot=$(allocate_slot "$name")
    mkdir -p "$dir"
    chown "$BENCH_USER:" "$dir"
    local port=$((3100 + slot)) redis_port=$((6400 + slot))
    cat >"$dir/meta.new" <<EOF
NAME=$name
BRANCH=$branch
SLOT=$slot
PORT=$port
REDIS_PORT=$redis_port
DB_NAME=$(db_name_for "$name")
HOST=$(env_host "$name")
CREATED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF
    mv "$dir/meta.new" "$dir/meta"
  )
  load_env_meta "$name"
  log "creating environment $name (slot $SLOT, port $PORT, db $DB_NAME)"
  local base_sha
  base_sha=$(cat "$STATE_DIR/base.sha")
  rm -rf "$dir/src"
  git -C "$REPO_DIR" worktree prune
  as_bench git -C "$REPO_DIR" worktree add --quiet --detach "$dir/src" "$base_sha"
  copy_build_state "$dir/src"
  echo "$base_sha" >"$dir/built.sha"
  timing create_worktree $(($(now_s) - start))
  start=$(now_s)
  write_env_file "$name" "$(random_hex 32)"
  clone_database "$name"
  timing create_database $(($(now_s) - start))
  regen_caddy
}

# Deploys sha to the environment, creating it first if needed. Keeps the database on later pushes.
deploy_env() {
  local name=$1 branch=$2 sha=$3 total_start created=0
  total_start=$(now_s)
  valid_env_name "$name" || die "invalid environment name '$name'"
  lock_exclusive "env-$name"
  local start
  start=$(now_s)
  fetch_commit "$branch" "$sha"
  timing fetch $(($(now_s) - start))
  if ! env_exists "$name"; then
    create_env "$name" "$branch"
    created=1
  fi
  load_env_meta "$name"
  local dir tree built base_sha
  dir=$(env_dir "$name")
  tree="$dir/src"
  built=$(cat "$dir/built.sha")
  base_sha=$(cat "$STATE_DIR/base.sha")

  start=$(now_s)
  as_bench git -C "$tree" checkout --quiet --force --detach "$sha"
  mapfile -t changed < <(git -C "$tree" diff --name-only "$built" "$sha")
  plan_build "${changed[@]}"
  log "$name: ${#changed[@]} files changed since ${built:0:12}; build set: ${BUILD_SET[*]:-none}"
  if [[ $DEPS_CHANGED == 1 ]]; then
    log "dependency manifests changed: reinstalling node_modules"
    find "$tree" -name node_modules -type d -prune -exec rm -rf {} +
    install_dependencies "$tree"
  fi
  timing checkout $(($(now_s) - start))

  start=$(now_s)
  build_tree "$tree" "$base_sha" incremental "${BUILD_SET[@]}"
  timing build_total $(($(now_s) - start))

  start=$(now_s)
  if touches_schema "$tree" "$base_sha"; then
    log "$name: commit touches the DB schema or standard metadata: running upgrade"
    services stop "$name"
    twenty_command "$name" "$tree" upgrade >"$LOG_DIR/upgrade-$name.log" 2>&1 || log "upgrade reported errors (see $LOG_DIR/upgrade-$name.log)"
    twenty_command "$name" "$tree" cache:flush >/dev/null 2>&1 || true
  fi
  services restart "$name"
  wait_ready "$name" 300 || die "$name did not become ready"
  timing restart_ready $(($(now_s) - start))
  echo "$sha" >"$dir/built.sha"
  echo "$branch" >"$dir/branch"
  timing total $(($(now_s) - total_start))
  record_event deploy "$name" "$sha" "$created"
}

touches_schema() {
  local tree=$1 base_sha=$2
  git -C "$tree" diff --name-only "$base_sha" HEAD -- packages/twenty-server/src |
    grep -Eq '(\.entity\.ts$|\.workspace-entity\.ts$|/database/|/twenty-standard-application/|upgrade-version-command)'
}

record_event() {
  local kind=$1 name=$2 sha=$3 created=${4:-0} line
  line=$(printf '{"at":"%s","kind":"%s","env":"%s","sha":"%s","created":%s,"timings":%s}' \
    "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$kind" "$name" "$sha" "$created" "$(timings_json)")
  echo "$line" >>"$LOG_DIR/events.jsonl"
  echo "BENCH_RESULT $line"
}

action_reset_db() {
  local name=$1 start
  start=$(now_s)
  lock_exclusive "env-$name"
  env_exists "$name" || die "no preview '$name'"
  services stop "$name"
  clone_database "$name"
  flush_redis "$name"
  services restart "$name"
  wait_ready "$name" 300 || die "$name did not become ready after reset"
  timing total $(($(now_s) - start))
  record_event reset-db "$name" "$(cat "$(env_dir "$name")/built.sha")"
}

action_rotate_auth_secret() {
  local name=$1 start before_token
  start=$(now_s)
  lock_exclusive "env-$name"
  env_exists "$name" || die "no preview '$name'"
  load_env_meta "$name"
  before_token=$(auth_refresh_token "$name" member) || die "pre-action sign-in failed"
  write_env_file "$name" "$(random_hex 32)"
  services stop "$name"
  psql_db "$DB_NAME" -f "$INFRA_DIR/box/sql/logout.sql" >/dev/null
  flush_redis "$name"
  services restart "$name"
  wait_ready "$name" 300 || die "$name did not become ready after logout"
  verify_logout "$name" "$before_token"
  timing total $(($(now_s) - start))
  record_event rotate-auth-secret "$name" "$(cat "$(env_dir "$name")/built.sha")"
}

teardown_env() {
  local name=$1
  [[ $name != main ]] || die "refusing to tear down main"
  lock_exclusive "env-$name"
  if ! env_exists "$name" && [[ ! -d $(env_dir "$name") ]]; then
    log "preview $name already gone"
    return 0
  fi
  systemctl stop "twenty-server@$name" "twenty-worker@$name" "twenty-redis@$name" 2>/dev/null || true
  local db
  db=$(db_name_for "$name")
  load_bench_secrets
  psql_admin -c "DROP DATABASE IF EXISTS \"$db\" WITH (FORCE)"
  if [[ -d "$(env_dir "$name")/src" ]]; then
    git -C "$REPO_DIR" worktree remove --force "$(env_dir "$name")/src" 2>/dev/null || true
  fi
  rm -rf "$(env_dir "$name")" "$(env_secret_file "$name")" "$LOG_DIR/build/$name"
  git -C "$REPO_DIR" worktree prune
  git -C "$REPO_DIR" branch -D "bench/$name" >/dev/null 2>&1 || true
  regen_caddy
  record_event teardown "$name" "-"
}
